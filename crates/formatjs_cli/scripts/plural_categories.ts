import {writeFileSync} from 'node:fs'
import minimist from 'minimist'
import plurals from 'cldr-core/supplemental/plurals.json' with {type: 'json'}
import cldrPackage from 'cldr-core/package.json' with {type: 'json'}

interface Args extends minimist.ParsedArgs {
  out: string
}

const ORDER = ['zero', 'one', 'two', 'few', 'many', 'other']
const cardinal = plurals.supplemental['plurals-type-cardinal'] as Record<
  string,
  Record<string, string>
>

function main({out}: Args) {
  if (!out) throw new Error('--out is required')
  const rows = Object.keys(cardinal)
    .sort()
    .map(locale => {
      const used = new Set(
        Object.keys(cardinal[locale]).map(key =>
          key.replace('pluralRule-count-', '')
        )
      )
      const categories = ORDER.filter(category => used.has(category))
        .map(category => JSON.stringify(category))
        .join(', ')
      return `    (${JSON.stringify(locale)}, &[${categories}]),`
    })
  writeFileSync(
    out,
    `// @generated by crates/formatjs_cli/scripts/plural_categories.ts from cldr-core ${cldrPackage.version}.
// Run \`bazel run //crates/formatjs_cli:plural_categories_data\` to update.

pub const CLDR_VERSION: &str = ${JSON.stringify(cldrPackage.version)};

pub const CARDINAL: &[(&str, &[&str])] = &[
${rows.join('\n')}
];
`
  )
}

main(minimist<Args>(process.argv.slice(2)))
