import minimist from 'minimist'
import {outputFileSync} from 'fs-extra/esm'
import packed from '@formatjs_generated/tz/all-tz.js'
import links from '@formatjs_generated/tz/links.js'
import primary from '@formatjs_generated/tz/primary.js'

interface Args extends minimist.ParsedArgs {
  out: string
}
function main(args: Args): void {
  const identifiers = [
    ...new Set([
      ...packed.zones.map(zone => zone.slice(0, zone.indexOf('|'))),
      ...Object.keys(links),
      ...Object.keys(primary),
      'UTC',
    ]),
  ].sort((a, b) => (a.toLowerCase() < b.toLowerCase() ? -1 : 1))
  const rows = identifiers.map(
    id =>
      `    (${JSON.stringify(id)}, ${JSON.stringify(primary[id as keyof typeof primary] ?? id)}),`
  )
  outputFileSync(
    args.out,
    `// @generated by //crates/temporal:identifiers from pinned IANA/CLDR data.\npub(super) static IDENTIFIERS: &[(&str, &str)] = &[\n${rows.join('\n')}\n];\n`
  )
}
if (import.meta.filename === process.argv[1])
  main(minimist<Args>(process.argv.slice(2)))
