import {mkdirSync, writeFileSync} from 'node:fs'
import {dirname} from 'node:path'
import minimist from 'minimist'
import {calendars} from '@formatjs_generated/cldr.locale/calendars.js'
import {hourCycles} from '@formatjs_generated/cldr.locale/hour-cycles.js'
import {numberingSystems} from '@formatjs_generated/cldr.locale/numbering-systems.js'
import {timezones} from '@formatjs_generated/cldr.locale/timezones.js'
import {weekData} from '@formatjs_generated/cldr.locale/week-data.js'
import {scriptDirections} from '@formatjs_generated/cldr.locale/script-directions.js'
import {likelySubtags} from '@formatjs_generated/cldr.core/likelySubtags.js'

interface Args extends minimist.ParsedArgs {
  out: string
}

function listTable(name: string, data: Record<string, readonly string[]>) {
  return `pub static ${name}: &[(&str, &[&str])] = &[\n${Object.keys(data)
    .sort()
    .map(
      key =>
        `(${JSON.stringify(key)}, &[${data[key].map(value => JSON.stringify(value)).join(',')}]),`
    )
    .join('\n')}\n];`
}

function stringTable(name: string, data: Record<string, string>) {
  return `pub static ${name}: &[(&str, &str)] = &[\n${Object.keys(data)
    .sort()
    .map(key => `(${JSON.stringify(key)}, ${JSON.stringify(data[key])}),`)
    .join('\n')}\n];`
}

function main(args: Args) {
  const source = [
    '// @generated by //crates/intl_locale:data. Do not edit.',
    listTable('CALENDARS', calendars),
    listTable('HOUR_CYCLES', hourCycles),
    listTable('NUMBERING_SYSTEMS', numberingSystems),
    listTable('TIME_ZONES', timezones),
    stringTable(
      'SCRIPT_DIRECTIONS',
      scriptDirections as Record<string, string>
    ),
    stringTable('LIKELY_SUBTAGS', likelySubtags),
    'pub static WEEK_DATA: &[(&str, (u8, &[u8]))] = &[',
    ...Object.keys(weekData)
      .sort()
      .map(key => {
        const value = weekData[key as keyof typeof weekData]
        return `(${JSON.stringify(key)}, (${value.firstDay}, &[${value.weekend.join(',')}])),`
      }),
    '];',
    '',
  ].join('\n')
  mkdirSync(dirname(args.out), {recursive: true})
  writeFileSync(args.out, source)
}

if (import.meta.filename === process.argv[1])
  main(minimist<Args>(process.argv.slice(2)))
