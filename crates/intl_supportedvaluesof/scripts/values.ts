import {mkdirSync, writeFileSync} from 'node:fs'
import {dirname} from 'node:path'
import minimist from 'minimist'
import {calendars} from '@formatjs_generated/cldr.supported-values/calendars.js'
import {collations} from '@formatjs_generated/cldr.supported-values/collations.js'
import {currencies} from '@formatjs_generated/cldr.supported-values/currencies.js'
import {timezones} from '@formatjs_generated/cldr.supported-values/timezones.js'
import {units} from '@formatjs_generated/cldr.supported-values/units.js'
import {numberingSystemNames} from '@formatjs_generated/cldr.number/numbering-systems.js'
import {collationCandidateLocales} from '@formatjs_generated/cldr.collation/locale-data.js'

interface Args extends minimist.ParsedArgs {
  out: string
}

function main(args: Args) {
  const lists: Record<string, readonly string[]> = {
    CALENDARS: calendars,
    COLLATIONS: collations,
    CURRENCIES: currencies,
    NUMBERING_SYSTEMS: numberingSystemNames,
    TIME_ZONES: timezones,
    UNITS: units,
  }
  const source = [
    '// @generated by //crates/intl_supportedvaluesof:values. Do not edit.',
    ...Object.entries(lists).map(
      ([name, values]) =>
        `pub static ${name}: &[&str] = &[${values.map(value => JSON.stringify(value)).join(',')}];`
    ),
    'pub static COLLATION_LOCALES: &[(&str, &[&str])] = &[',
    ...Object.entries(collationCandidateLocales)
      .sort(([left], [right]) => left.localeCompare(right))
      .map(
        ([value, locales]) =>
          `(${JSON.stringify(value)}, &[${locales.map(locale => JSON.stringify(locale)).join(',')}]),`
      ),
    '];',
    '',
  ].join('\n')
  mkdirSync(dirname(args.out), {recursive: true})
  writeFileSync(args.out, source)
}

if (import.meta.filename === process.argv[1]) {
  main(minimist<Args>(process.argv.slice(2)))
}
